# frozen_string_literal: true

require "json"

module ThreePassReview
  module Eval
    # Rescores every run with the current labels and rewrites the README block
    # between the eval markers. Only runs made against the real API, on the
    # current dataset version, ever reach the README.
    class Report
      START = "<!-- eval:start -->"
      FINISH = "<!-- eval:end -->"
      PASS_ROWS = {"correctness" => "Correctness pass", "security" => "Security and data safety pass",
                   "architecture" => "Architecture pass"}.freeze

      def initialize(results_root:, cases:, labels_dir:, dataset_version:, readme_path: nil)
        @results_root = results_root
        @cases = cases
        @labels_dir = labels_dir
        @dataset_version = dataset_version
        @readme_path = readme_path
      end

      def run(io: $stdout)
        labels = Labels.new(@labels_dir)
        runs = Dir[File.join(@results_root, "*", "records.json")].sort.filter_map do |path|
          data = JSON.parse(File.read(path))
          meta = data["meta"]
          # A run is only ever scored against the dataset it ran on; its
          # summary keeps the numbers it had.
          if meta["dataset_version"] != @dataset_version
            io.puts "#{meta["run_id"]}: skipped, made on dataset #{meta["dataset_version"]} (now #{@dataset_version})"
            next
          end
          score = Eval.scorer(@cases, data["records"], labels, meta).score
          Summary.write(File.dirname(path), meta, score)
          io.puts "#{meta["run_id"]} (#{meta["client"]}): recall #{Summary.proportion(score.dig("recall", "strict"))}, " \
            "precision #{Summary.precision_text(score["precision"])}"
          {"meta" => meta, "score" => score}
        end
        io.puts "No runs on the current dataset in #{@results_root}." if runs.empty?
        publish(runs, io)
      end

      def table(runs)
        latest = runs.group_by { |r| r.dig("meta", "config") }
          .transform_values { |list| list.max_by { |r| [r.dig("meta", "started_at").to_s, r.dig("meta", "run_id")] } }
        main = latest["independent"]
        return nil unless main

        score = main["score"]
        rows = PASS_ROWS.filter_map do |pass, label|
          v = score.dig("per_pass", pass) or next
          row(label, v.dig("recall_own_category", "strict"), v["precision"], v["cost_usd"])
        end
        rows << row("**Reconciled output**", score.dig("recall", "strict"), score["precision"], score["cost_usd"])
        cases = score["cases"]
        meta = main["meta"]
        lines = ["| | Recall (95% CI) | Precision (95% CI) | False positives per clean PR | Cost per review (median / p90) |",
          "|---|---|---|---|---|", *rows, ""]
        if latest.size > 1
          lines += ["| Configuration | Recall (95% CI) | Precision (95% CI) | Cost per review (median / p90) |", "|---|---|---|---|"]
          latest.sort.each do |name, r|
            s = r["score"]
            lines << "| #{name} | #{Summary.proportion(s.dig("recall", "strict"))} | #{Summary.precision_text(s["precision"])} | " \
              "#{Summary.usd(s.dig("cost_usd", "median"))} / #{Summary.usd(s.dig("cost_usd", "p90"))} |"
          end
          lines << ""
        end
        lines << "_Generated by `rake eval:report` from `evals/results/#{meta["run_id"]}`. Never edited by hand. " \
          "Dataset: #{cases["total"]} cases (#{cases["real"]} real, #{cases["planted"]} planted, #{cases["clean"]} clean), " \
          "version #{meta["dataset_version"]}. Model #{meta["model"]}, #{meta["runs"]} runs per case, #{meta["date"]}._"
        lines.join("\n")
      end

      private

      def row(label, recall, precision, cost)
        "| #{label} | #{Summary.proportion(recall)} | #{Summary.precision_text(precision)} | #{Summary.fp_text(precision)} | " \
          "#{Summary.usd(cost["median"])} / #{Summary.usd(cost["p90"])} |"
      end

      def publish(runs, io)
        return unless @readme_path

        text = table(runs.select { |r| r.dig("meta", "client") == "anthropic" })
        unless text
          io.puts "README not updated: no independent run against the real API on the current dataset."
          return
        end
        readme = File.read(@readme_path)
        start = readme.index(START) or raise Error, "#{@readme_path} has no #{START} marker"
        finish = readme.index(FINISH) or raise Error, "#{@readme_path} has no #{FINISH} marker"
        File.write(@readme_path, "#{readme[0...start]}#{START}\n#{text}\n#{readme[finish..]}")
        io.puts "README results table updated."
      end
    end
  end
end
