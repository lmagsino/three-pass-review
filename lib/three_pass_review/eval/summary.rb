# frozen_string_literal: true

require "json"

module ThreePassReview
  module Eval
    # Writes summary.json and a readable summary.md for one run, and
    # misses.md once (people fill in the reasons, so it's never overwritten).
    module Summary
      module_function

      def write(dir, meta, score)
        File.write(File.join(dir, "summary.json"), JSON.pretty_generate("meta" => meta, "metrics" => score))
        File.write(File.join(dir, "summary.md"), markdown(meta, score))
        misses = File.join(dir, "misses.md")
        File.write(misses, misses_markdown(meta, score)) unless File.exist?(misses)
      end

      def pct(rate)
        rate.nil? ? "n/a" : "#{(rate * 100).round}%"
      end

      # "62% (48–75%), n=24", or "5 of 7" when n is too small for a percentage.
      def proportion(p)
        return "n/a" if p.nil?
        return p["text"] if p["text"]
        return "#{p["k"]} of #{p["n"]}" if p["n"].to_i < Scorer::SMALL_N

        lo, hi = p["ci95"]
        "#{pct(p["rate"])} (#{pct(lo).delete("%")}–#{pct(hi)}), n=#{p["n"]}"
      end

      def usd(value)
        value.nil? ? "n/a" : format("$%.3f", value)
      end

      def precision_text(precision)
        return proportion(precision["value"]) if precision["value"]

        format("unverified: %.1f per PR (%s unlabeled)", precision["unverified_per_pr"].to_f, pct(precision["unlabeled_share"]))
      end

      def fp_text(precision)
        fp = precision["false_positives_per_clean_pr"]
        fp ? format("%.2f (n=%d)", fp["value"], fp["n"]) : "pending labels"
      end

      def markdown(meta, s)
        cases = s["cases"]
        lines = []
        lines << "# Eval run #{meta["run_id"]}"
        lines << ""
        lines << "**Generated by `rake eval:run` / `rake eval:report`. Don't edit by hand.**#{" Fake client: these numbers are not real results." if meta["client"] == "fake"}"
        lines << ""
        lines << "| | |"
        lines << "|---|---|"
        {
          "Config" => "#{meta["config"]} (#{meta["mode"]}), #{meta["runs"]} runs per case",
          "Client" => meta["client"], "Model" => meta["model"],
          "Sampling" => "effort #{meta.dig("sampling", "effort") || "API default"}, max_output_tokens #{meta.dig("sampling", "max_output_tokens")}",
          "Prompts" => meta["prompts_version"], "Dataset" => "#{cases["total"]} cases (#{cases["real"]} real, #{cases["planted"]} planted, #{cases["clean"]} clean), #{cases["defects"]} defects, version #{meta["dataset_version"]}",
          "Code" => meta["git_sha"], "Date" => meta["date"]
        }.each { |k, v| lines << "| #{k} | #{v} |" }
        r = s["recall"]
        lines += ["", "## Recall", "", "A defect counts as caught when a majority of its case's runs catch it.", "",
          "| | Strict (file, lines, category) | Lenient (file, lines) |", "|---|---|---|",
          "| Reconciled | #{proportion(r["strict"])} | #{proportion(r["lenient"])} |"]
        stab = r["stability"]
        lines << "" << "Stability: strict recall per run ranged #{pct(stab["min"])} to #{pct(stab["max"])}." if stab
        lines += ["", "| Category | Recall (strict) |", "|---|---|"] + r["by_category"].map { |k, v| "| #{k} | #{proportion(v)} |" }
        lines += ["", "| Subcategory | Recall (strict) |", "|---|---|"] + r["by_subcategory"].map { |k, v| "| #{k} | #{proportion(v)} |" }
        if r["by_cutoff"]
          lines += ["", "Relative to the model's training cutoff (#{meta["model_training_cutoff"]}):", "",
            "| Merged | Recall (strict) |", "|---|---|"] + r["by_cutoff"].map { |k, v| "| #{k} | #{proportion(v)} |" }
        end
        p = s["precision"]
        lines += ["", "## Precision", "", "Reconciled: #{precision_text(p)}. False positives per clean PR: #{fp_text(p)}.",
          "Labels: #{p["labels"].map { |k, v| "#{v} #{k}" }.join(", ").then { |t| t.empty? ? "none needed" : t }} (#{p["matched"]} of #{p["findings"]} findings matched a known defect)."]
        lines += ["", "## Per pass, before reconciliation", "",
          "| Pass | Recall, own category | Recall, all defects | Precision | Cost (median / p90) |", "|---|---|---|---|---|"]
        s["per_pass"].each do |name, v|
          lines << "| #{name} | #{proportion(v.dig("recall_own_category", "strict"))} | #{proportion(v.dig("recall_all", "strict"))} | " \
            "#{precision_text(v["precision"])} | #{usd(v.dig("cost_usd", "median"))} / #{usd(v.dig("cost_usd", "p90"))} |"
        end
        c = s["cost_usd"]
        lines += ["", "## Cost and latency", "",
          "Cost per review: median #{usd(c["median"])}, p90 #{usd(c["p90"])}, max #{usd(c["max"])} (n=#{c["n"]}).",
          "Cost ceiling degraded or refused #{proportion(s["ceiling_hits"])} reviews (#{s["refused"]} refused).",
          format("Latency: median %.1fs, p90 %.1fs.", s.dig("latency_s", "median").to_f, s.dig("latency_s", "p90").to_f)]
        lines += ["", "## Threshold sweep", "", "| Threshold | Recall (strict) | Precision |", "|---|---|---|"]
        s["threshold_sweep"].each do |t, v|
          lines << "| #{t} | #{proportion(v["recall"])} | #{v["precision"] ? proportion(v["precision"]) : "unverified"} |"
        end
        lines << "" << "Missed defects: #{s["misses"].size}. Reasons go in misses.md."
        "#{lines.join("\n")}\n"
      end

      def misses_markdown(meta, s)
        body = s["misses"].map do |m|
          "- **#{m["case"]} / #{m["defect"]}** (#{m["category"]}/#{m["subcategory"]}): #{m["description"]} " \
            "Caught in #{m["caught_in_runs"]} of #{meta["runs"]} runs. Reason: _to fill in_"
        end
        "# Missed defects, #{meta["run_id"]}\n\nOne line each on why the reviewer missed it.\n\n#{body.join("\n")}\n"
      end
    end
  end
end
